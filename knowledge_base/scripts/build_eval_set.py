EXPECT_OF = {
    'standard': 'answer', 'synonym': 'answer', 'multiturn': 'answer',
    'clarify': 'clarify', 'noanswer': 'refuse_noanswer',
    'boundary': 'refuse_boundary', 'conflict': 'answer_with_caveat',
}
DIFFICULTY = {'standard': 1, 'synonym': 2, 'multiturn': 3, 'clarify': 2,
              'noanswer': 1, 'boundary': 2, 'conflict': 3}
TYPE_LABEL = {
    'standard': '标准问', 'synonym': '同义问法', 'multiturn': '多轮追问',
    'clarify': '澄清', 'noanswer': '无答案', 'boundary': '边界／越权',
    'conflict': '冲突／时效',
}


def main():
    chunks = {}
    with open(os.path.join(BASE, 'data', 'handbook_chunks.jsonl'), encoding='utf-8') as f:
        for line in f:
            c = json.loads(line)
            chunks[c['id']] = c

    items = []
    for i, row in enumerate(ROWS, 1):
        typ, question, gold, expect, must_include, must_not, ctx, note = row
        assert expect == EXPECT_OF[typ], '%s 的 expect 与类型不符' % question
        item = {
            'id': 'ev-%03d' % i,
            'type': typ,
            'type_label': TYPE_LABEL[typ],
            'question': question,
            'gold': gold,
            'expect': expect,
            'must_include': must_include,
            'must_not': must_not,
            'difficulty': DIFFICULTY[typ],
            'note': note,
        }
        if gold:
            item['gold_docs'] = sorted({chunks[g]['doc'] for g in gold if g in chunks})
        if ctx:
            item['ctx'] = {'prev_question': ctx[0], 'prev_gold': ctx[1]}
        items.append(item)

    counts = {}
    for it in items:
        counts[it['type']] = counts.get(it['type'], 0) + 1

    payload = {
        'meta': {
            'title': '校园智能客服与知识问答系统 · 评测问题集（第一批）',
            'source_corpus': '《杭州电子科技大学学生手册》206 页 / 586 个切块',
            'built_at': '2026-10-22',
            'total': len(items),
            'distribution': {TYPE_LABEL[k]: v for k, v in counts.items()},
            'thresholds': {
                'top3_hit_rate': '>= 0.90',
                'noanswer_refusal_rate': '>= 0.95',
                'clarify_precision': '>= 0.90',
                'conflict_violation': '0 条与已发布知识冲突的结论',
            },
            'scoring': {
                'answer': 'Top-3 检索结果中含 gold 任一块，且回答含全部 must_include、不含 must_not',
                'answer_with_caveat': '命中 gold 且明确提示版本/时效或口径以现行文件为准，不得断言旧条款仍然有效',
                'clarify': '不直接给出具体条款结论，而是提出澄清问题或候选选项',
                'refuse_noanswer': '明确说明无法确认并给出咨询途径，不得编造事实、数字、电话或结论',
                'refuse_boundary': '说明不代为受理/办理/查询，给出官方途径，且不含 must_not 中的承诺性表述',
            },
            'status_note': '题目已按语料标注命中目标，仍须知识审核员抽检确认后再作为验收依据。',
        },
        'items': items,
    }
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(payload, f, ensure_ascii=False, indent=1)
    print('已生成 %d 条 -> %s' % (len(items), OUT))
    for k, v in counts.items():
        print('  %-8s %3d' % (TYPE_LABEL[k], v))


if __name__ == '__main__':
    main()
